function escapeCell(text) {
  return text.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}

function paramTable(shortcode, enums) {
  const rows = shortcode.params.filter((p) => p.inCode || p.documented);
  if (rows.length === 0) return [];

  const out = ["| Parameter | Type | Notes |", "| --- | --- | --- |"];
  for (const p of rows) {
    const notes = [];
    if (p.required) notes.push("**Required.**");
    if (p.desc) {
      notes.push(
        escapeCell(
          p.desc
            .replace(/\s*Required\.\s*/, " ")
            .replace(/\s*Defaults? (?:to )?[^.]+\.\s*/i, " ")
            .replace(/\s*One of [^.]+\.\s*/i, " ")
            .trim()
        )
      );
    }

    const choices = enums.get(p.name) ?? p.enum;
    // A boolean's "one of true, false" carries no information the type lacks.
    const informative = choices?.length && !choices.every((c) => /^(true|false)$/.test(c));
    if (informative) notes.push(`One of \`${choices.join("`, `")}\`.`);
    // `| default ""` is an implementation detail, not a documented default.
    if (p.default) notes.push(`Default \`${p.default}\`.`);
    if (p.positionalAlias) notes.push("Also accepted as the first positional argument.");
    if (p.alias) notes.push(`Deprecated alias: \`${p.alias}\`.`);
    if (p.deprecated !== undefined) notes.push(`**Deprecated.** ${p.deprecated}`.trim());
    if (!p.documented) notes.push("_Undocumented in the template._");
    if (p.documented && !p.inCode) notes.push("_Documented but not read by the template._");

    out.push(`| \`${p.name}\` | ${p.type || "string"} | ${notes.join(" ") || "—"} |`);
  }
  return [...out, ""];
}

function renderShortcode(shortcode, snippets) {
  const mine = snippets.filter((s) => s.owner === shortcode.name);
  const enums = new Map();
  for (const s of mine) for (const [k, v] of s.enums) if (!enums.has(k)) enums.set(k, v);

  const notation = shortcode.percentNotation ? "{{% %}}" : "{{< >}}";
  const facts = [notation, shortcode.paired ? "paired" : "self-closing"];
  if (shortcode.positional.length > 0) facts.push("accepts positional arguments");
  if (shortcode.network) facts.push("fetches at build time");

  const out = [`### ${shortcode.name}`, "", facts.join(" · "), ""];
  if (shortcode.description) out.push(shortcode.description, "");

  out.push(...paramTable(shortcode, enums));

  if (shortcode.positionalDocs.length > 0) {
    out.push(`Positional: ${shortcode.positionalDocs.join(" ")}`, "");
  }

  if (shortcode.parentParams.length > 0) {
    out.push(`Reads from its parent: ${shortcode.parentParams.map((p) => `\`${p}\``).join(", ")}.`, "");
  }

  // Prefer a snippet example: it is complete and shows a child shortcode in
  // place, where `@example` is a single line.
  const examples = mine.length > 0 ? mine.map((s) => s.example) : shortcode.examples;
  if (examples.length > 0) {
    const fence = examples.some((e) => e.includes("```")) ? "````" : "```";
    out.push(`${fence}markdown`, examples.join("\n\n"), fence, "");
  }

  if (shortcode.siteParams.length > 0) {
    out.push(`Site config: ${shortcode.siteParams.map((p) => `\`params.${p}\``).join(", ")}.`, "");
  }

  return out.join("\n");
}

function renderSnippetEntry(snippet) {
  const isYaml = !snippet.example.startsWith("```") && !snippet.example.startsWith("$$");
  const fence = snippet.example.includes("```") ? "````" : "```";
  return [`### ${snippet.label}`, "", snippet.description, "", `${fence}${isYaml ? "yaml" : "markdown"}`, snippet.example, fence, ""].join("\n");
}

function buildShortcodes(shortcodes, snippets) {
  const byName = new Map(shortcodes.map((s) => [s.name, s]));
  const byPrefix = new Map(snippets.map((s) => [s.prefix, s]));
  const placed = new Set();

  const parts = [
    BANNER("layouts/_shortcodes/ and .vscode/hextra.code-snippets"),
    "",
    "# Shortcode reference",
    "",
    `Every shortcode the theme ships: ${shortcodes.length} of them, with parameters taken from the templates in \`layouts/_shortcodes/\` and examples from the theme's editor snippets.`,
    "",
    "## Rules that apply throughout",
    "",
    "- **Notation is not interchangeable.** A shortcode listed as `{{% %}}` renders its body as Markdown and breaks when written with angle brackets. The `{{% %}}` shortcodes are: " +
      shortcodes
        .filter((s) => s.percentNotation)
        .map((s) => `\`${s.name}\``)
        .join(", ") +
      ".",
    "- **A paired shortcode needs a closing tag.** Self-closing ones must not have one.",
    "- **Icon names are a closed set.** Any `icon`, `tagIcon`, or `badgeIcon` value must appear in `icons.md`. An unknown name renders nothing and raises no error.",
    "- **Build-time fetching can be switched off.** The shortcodes marked _fetches at build time_ all go quiet when `params.remoteFetch.enable` is `false`.",
    "",
  ];

  for (const category of CATEGORIES) {
    const found = category.names.map((n) => byName.get(n)).filter(Boolean);
    if (found.length === 0) continue;
    found.forEach((s) => placed.add(s.name));
    parts.push(`## ${category.title}`, "", category.blurb, "");
    for (const shortcode of found) parts.push(renderShortcode(shortcode, snippets));
  }

  const orphans = shortcodes.filter((s) => !placed.has(s.name));
  if (orphans.length > 0) {
    parts.push("## Uncategorized", "", "Add these to `CATEGORIES` in `scripts/build-skill.mjs`.", "");
    for (const shortcode of orphans) parts.push(renderShortcode(shortcode, snippets));
  }

  for (const section of SNIPPET_SECTIONS) {
    const found = section.prefixes.map((p) => byPrefix.get(p)).filter(Boolean);
    if (found.length === 0) continue;
    parts.push(`## ${section.title}`, "", section.blurb, "");
    for (const snippet of found) parts.push(renderSnippetEntry(snippet));
  }

  return (
    parts
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

