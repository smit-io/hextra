function cleanBody(lines) {
  return (
    lines
      .join("\n")
      // Collapse a choice to its first option so the example is valid, pasteable
      // code. The full list of options reaches the reader through the parameter
      // table, which is built from the same placeholder.
      .replace(/\$\{\d+\|([^|]*)\|\}/g, (_, choices) => choices.split(",")[0].trim())
      .replace(/\$\{\d+:([^}]*)\}/g, "$1")
      .replace(/\$\{\d+\}/g, "")
      .replace(/\$\d+/g, "")
      .replace(/\\\$/g, "$")
      .replace(/[ \t]+$/gm, "")
      .replace(/\n{3,}/g, "\n\n")
      .trim()
  );
}

/** Enum choices a snippet spells out, keyed by parameter name. */
function snippetEnums(rawBody) {
  const out = new Map();
  const re = /([\w-]+)=\\?"?\$\{\d+\|([^|]*)\|\}/g;
  for (const m of rawBody.matchAll(re)) {
    out.set(
      m[1],
      m[2].split(",").map((v) => v.trim())
    );
  }
  return out;
}

function loadSnippets() {
  const raw = JSON.parse(readFileSync(snippetsFile, "utf8"));
  return Object.entries(raw).map(([label, snippet]) => {
    const rawBody = snippet.body.join("\n");
    const example = cleanBody(snippet.body);
    const owner = example.match(/\{\{[<%]\s*([\w/-]+)/)?.[1] ?? null;
    return {
      label: label.replace(/^Hextra:\s*/, ""),
      prefix: snippet.prefix,
      description: snippet.description,
      example,
      enums: snippetEnums(rawBody),
      owner,
    };
  });
}

