function docsGaps() {
  const skillText = walk(join(root, "skills", "hextra"))
    .filter((f) => f.endsWith(".md"))
    .map((f) => readFileSync(f, "utf8"))
    .join("\n");

  const gaps = [];
  for (const topic of DOCS_TOPICS) {
    if (topic.skip) continue;
    if (!topic.probe.test(skillText)) {
      gaps.push(`docs/content/docs/${topic.page}.md has no counterpart in the skill`);
    }
  }
  return gaps;
}

// ---------------------------------------------------------------------------
// Hugo's own shortcodes
// ---------------------------------------------------------------------------

// Hugo's embedded shortcodes as of v0.141+. Sourced from
// https://gohugo.io/shortcodes/ — there is no way to read them out of the
// binary, so this list is maintained by hand and checked two ways: every name
// must be documented in hugo-shortcodes.md, and any theme shortcode sharing a
// name shadows Hugo's and must be called out as a collision.
const HUGO_BUILTINS = ["details", "figure", "highlight", "instagram", "param", "qr", "ref", "relref", "vimeo", "x", "youtube"];

function hugoShortcodeGaps(shortcodes) {
  const file = join(outDir, "hugo-shortcodes.md");
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    return ["hugo-shortcodes.md is missing"];
  }

  const gaps = [];
  for (const name of HUGO_BUILTINS) {
    if (!new RegExp(`^###?\\s+${name}\\b|\`${name}\``, "m").test(text)) {
      gaps.push(`hugo-shortcodes.md does not document Hugo's '${name}'`);
    }
  }

  // A theme shortcode with the same name wins, and silent shadowing is the
  // trap. Every built-in is named somewhere in this file by design, so the
  // check has to look inside the collisions section specifically.
  const collisions = text.match(/^## Name collisions[^]*?(?=^## )/m)?.[0] ?? "";
  for (const shortcode of shortcodes) {
    if (!HUGO_BUILTINS.includes(shortcode.name)) continue;
    if (!new RegExp(`\`${shortcode.name}\``).test(collisions)) {
      gaps.push(`'${shortcode.name}' shadows a Hugo built-in but is not listed under "Name collisions"`);
    }
  }
  return gaps;
}

// ---------------------------------------------------------------------------
// Plugin manifests
// ---------------------------------------------------------------------------

// The repo is installable as a Claude Code plugin, and is its own marketplace.
// VERSION is the repo's single source of truth — release.yml fires on it
// changing — so the manifests follow it rather than carrying a second number
// somebody has to remember. Only the version field is rewritten; every other
// field stays hand-editable.
const pluginDir = join(root, ".claude-plugin");
const pluginManifest = join(pluginDir, "plugin.json");
const marketplaceManifest = join(pluginDir, "marketplace.json");
const version = readFileSync(join(root, "VERSION"), "utf8").trim();

const serialize = (value) => JSON.stringify(value, null, 2) + "\n";

function buildPluginManifest() {
  const manifest = JSON.parse(readFileSync(pluginManifest, "utf8"));
  manifest.version = version;
  return serialize(manifest);
}

function buildMarketplaceManifest() {
  const manifest = JSON.parse(readFileSync(marketplaceManifest, "utf8"));
  for (const entry of manifest.plugins ?? []) {
    // Only this repo's own plugin tracks VERSION. An entry pointing at another
    // repository carries whatever version that repository published.
    if (typeof entry.source === "string" && entry.source.startsWith(".")) {
      entry.version = version;
    }
  }
  return serialize(manifest);
}

const KEBAB = /^[a-z0-9]+(-[a-z0-9]+)*$/;

function manifestGaps() {
  const gaps = [];
  let plugin;
  let marketplace;

  try {
    plugin = JSON.parse(readFileSync(pluginManifest, "utf8"));
  } catch (error) {
    return [`.claude-plugin/plugin.json is missing or invalid: ${error.message}`];
  }
  try {
    marketplace = JSON.parse(readFileSync(marketplaceManifest, "utf8"));
  } catch (error) {
    return [`.claude-plugin/marketplace.json is missing or invalid: ${error.message}`];
  }

  if (!KEBAB.test(plugin.name ?? "")) gaps.push(`plugin.json name '${plugin.name}' is not kebab-case`);
  if (!KEBAB.test(marketplace.name ?? "")) gaps.push(`marketplace.json name '${marketplace.name}' is not kebab-case`);
  if (!marketplace.owner?.name) gaps.push("marketplace.json is missing owner.name");

  const self = (marketplace.plugins ?? []).find((entry) => typeof entry.source === "string" && entry.source.startsWith("."));
  if (!self) {
    gaps.push("marketplace.json lists no plugin sourced from this repository");
  } else {
    // The entry's name is what users type in `/plugin install <name>@<market>`.
    // If it drifts from plugin.json the install resolves to nothing.
    if (self.name !== plugin.name) {
      gaps.push(`marketplace entry '${self.name}' does not match plugin.json name '${plugin.name}'`);
    }
    try {
      readFileSync(join(pluginDir, "..", self.source, ".claude-plugin", "plugin.json"));
    } catch {
      gaps.push(`marketplace entry source '${self.source}' has no .claude-plugin/plugin.json`);
    }
  }

  // Skills are namespaced <plugin>:<skill>, and a plugin's skills directory
  // defaults to ./skills/. A skill folder without SKILL.md installs as nothing.
  const skillsDir = join(root, "skills");
  const skills = readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);
  if (skills.length === 0) gaps.push("skills/ contains no skill directories");
  for (const skill of skills) {
    try {
      readFileSync(join(skillsDir, skill, "SKILL.md"));
    } catch {
      gaps.push(`skills/${skill}/ has no SKILL.md, so it installs as nothing`);
    }
  }

  return gaps;
}

// ---------------------------------------------------------------------------
// Cross-check
// ---------------------------------------------------------------------------

function mismatches(shortcodes, snippets) {
  const found = [];
  const byName = new Map(shortcodes.map((s) => [s.name, s]));

  for (const shortcode of shortcodes) {
    if (!shortcode.description && shortcode.params.length === 0 && shortcode.examples.length === 0) {
      found.push(`${shortcode.name}: template has no doc comment`);
    }
    for (const p of shortcode.params) {
      if (p.inCode && !p.documented) {
        found.push(`${shortcode.name}: reads '${p.name}' but has no @param for it`);
      }
      if (!p.inCode && p.documented && !shortcode.positional.length) {
        found.push(`${shortcode.name}: documents '${p.name}' but never reads it`);
      }
    }
  }

  // A snippet naming a parameter the template does not read is the failure
  // mode that hand-written snippets are prone to.
  for (const snippet of snippets) {
    const shortcode = snippet.owner ? byName.get(snippet.owner) : null;
    if (!shortcode) continue;
    const known = new Set(shortcode.params.map((p) => p.name));
    const opening = (snippet.example.match(/\{\{[<%]\s*[\w/-]+([^]*?)[%>]\}\}/)?.[1] ?? "")
      // A quoted value can itself contain `key=value` (`attributes="height=20"`).
      .replace(/"[^"]*"/g, '""');
    for (const m of opening.matchAll(/([\w-]+)=/g)) {
      if (!known.has(m[1])) {
        found.push(`${snippet.prefix}: uses '${m[1]}', which ${shortcode.name} does not read`);
      }
    }
  }

  return found;
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

const check = process.argv.includes("--check");
const strict = process.argv.includes("--strict");

const shortcodes = walk(shortcodeDir)
  .filter((f) => f.endsWith(".html"))
  .map(parseShortcode)
  .sort((a, b) => a.name.localeCompare(b.name));

const snippets = loadSnippets();

const outputs = [
  { path: join(outDir, "shortcodes.md"), content: buildShortcodes(shortcodes, snippets) },
  { path: join(outDir, "icons.md"), content: buildIcons(readFileSync(iconsFile, "utf8")) },
  { path: pluginManifest, content: buildPluginManifest() },
  { path: marketplaceManifest, content: buildMarketplaceManifest() },
];

let stale = 0;
for (const { path, content } of outputs) {
  const rel = relative(root, path);
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current === content) {
      console.log(`ok      ${rel}`);
    } else {
      console.error(`stale   ${rel}`);
      stale++;
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote   ${rel} (${content.split("\n").length} lines)`);
  }
}

const problems = [...mismatches(shortcodes, snippets), ...coverageGaps(), ...docsGaps(), ...hugoShortcodeGaps(shortcodes), ...manifestGaps()];
if (problems.length > 0) {
  console.error(`\n${problems.length} documentation gap(s) between the theme and the skill:`);
  for (const problem of problems) console.error(`  ${problem}`);
  console.error("\nThese do not fail the build unless --strict is passed.");
}

if (check && stale > 0) {
  console.error(`\n${stale} generated file(s) out of date. Run: npm run build:skill`);
  process.exit(1);
}
if (strict && problems.length > 0) process.exit(1);
