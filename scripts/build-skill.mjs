function buildIcons(yaml) {
  const names = yaml
    .split("\n")
    .map((line) => line.match(/^([A-Za-z0-9][\w-]*):/))
    .filter(Boolean)
    .map((m) => m[1])
    .sort();

  const columns = 4;
  const rows = Math.ceil(names.length / columns);
  const table = ["| | | | |", "| --- | --- | --- | --- |"];
  for (let r = 0; r < rows; r++) {
    const cells = [];
    for (let c = 0; c < columns; c++) {
      const name = names[c * rows + r];
      cells.push(name ? `\`${name}\`` : "");
    }
    table.push(`| ${cells.join(" | ")} |`);
  }

  return [
    BANNER("data/icons.yaml"),
    "",
    "# Icon names",
    "",
    `The ${names.length} icons bundled with the theme. Use a name from this list verbatim — an unknown name renders nothing, silently.`,
    "",
    "Valid wherever the theme takes an icon: the `icon` shortcode, and the `icon` parameter on `callout`, `card`, `cta`, `button`, `badge`, `accordion-item`, `timeline-item`, `stat`, `keyword`, `article`, `feature-card`, and the repository cards. Also `tagIcon` on `card`, `badgeIcon` on `timeline-item`, and `params.icon` on a `hugo.yaml` menu entry.",
    "",
    "```markdown",
    '{{< icon "sparkles" >}}',
    '{{< callout type="info" icon="lightning-bolt" >}}Heads up.{{< /callout >}}',
    "```",
    "",
    "Icons from an external provider are a separate path needing `params.icons.remote.enable`; see the `icon` entry in `shortcodes.md`.",
    "",
    "## Available names",
    "",
    ...table,
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// Coverage of the hand-written references
// ---------------------------------------------------------------------------

// The generated references cannot drift, because they are rebuilt from the
// templates. The hand-written ones can, so every param the layouts read is
// checked against the file that is supposed to document it. This does not
// generate prose — it only reports what nobody has written about yet.
const layoutsDir = join(root, "layouts");

// Params that are deliberately absent from the author-facing references.
const COVERAGE_IGNORE = {
  // Read from a menu entry's `params`, not from a page. Documented as part of
  // the menu reference in site-config.md instead.
  page: new Map([
    ["icon", "menu entry param"],
    ["label", "menu entry param"],
    ["type", "menu entry param"],
    ["separator", "menu entry param"],
    ["weight", "ordering, covered under Ordering"],
  ]),
  // Asset-path overrides consumed by script partials. Covered collectively by
  // the "Vendored asset overrides" section rather than key by key.
  site: new Map([["Author", "Hugo's own author config, not a theme param"]]),
};

function paramsFromLayouts() {
  const site = new Set();
  const page = new Set();
  for (const file of walk(layoutsDir)) {
    if (!/\.(html|xml|txt|md|json)$/.test(file)) continue;
    const src = readFileSync(file, "utf8");
    // Blank out site params first so the page pass cannot rematch them.
    const remaining = src.replace(/(?:site|\.Site)\.Params\.([A-Za-z][\w.]*)/g, (_, path) => {
      site.add(path.replace(/\.$/, ""));
      return "\u0000";
    });
    for (const m of remaining.matchAll(/\.Params\.([A-Za-z][\w.]*)/g)) {
      page.add(m[1].replace(/\.$/, ""));
    }
  }
  return { site: [...site].sort(), page: [...page].sort() };
}

/**
 * Is `path` (e.g. "blog.list.pagerSize") actually written about?
 *
 * A bare word search is too generous: "Author" matches the skill's own
 * description, "assets" matches any `assets/` path, "favicon" matched a table
 * row about `static/`. Requiring the leaf to appear as a YAML key, in
 * backticks, or in dotted form rejects that class of false positive.
 */
function documents(text, path) {
  const leaf = path.split(".").pop();
  const e = leaf.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(^|\\s)${e}:|\`[\\w.]*${e}[\\w.]*\`|\\.${e}\\b`, "m").test(text);
}

function coverageGaps() {
  const { site, page } = paramsFromLayouts();

  // Checked against the whole skill: a blog param may well be documented in
  // blog.md rather than site-config.md, and that counts.
  const skillText = walk(join(root, "skills", "hextra"))
    .filter((f) => f.endsWith(".md"))
    .map((f) => readFileSync(f, "utf8"))
    .join("\n");

  const gaps = [];
  for (const [kind, names] of [
    ["page", page],
    ["site", site],
  ]) {
    for (const path of names) {
      if (COVERAGE_IGNORE[kind].has(path.split(".")[0])) continue;
      if (!documents(skillText, path)) {
        gaps.push(`nothing documents the ${kind} param '${path}'`);
      }
    }
  }
  return gaps;
}

