#!/usr/bin/env node
// Generates the machine-derived half of the Hextra agent skill.
//
//   skills/hextra/references/shortcodes.md  <- layouts/_shortcodes/**/*.html
//                                              + .vscode/hextra.code-snippets
//   skills/hextra/references/icons.md       <- data/icons.yaml
//
// The shortcode templates are the authority: they define which parameters
// exist, which are required, what the defaults are, and whether a shortcode is
// paired. Their doc comments carry `@param` and `@example` tags, so most of the
// prose comes from the implementation too.
//
// The VS Code snippets are a secondary source, used for two things the
// templates express poorly: enum choices (a snippet writes
// `${1|grid,mosaic|}`, where a template only mentions them in prose) and
// complete copy-paste examples (a template's `@example` is one terse line, and
// a few are mangled by Prettier's Go-template parser). Snippets also cover
// front matter and code fences, which are not shortcodes at all.
//
// Where the two disagree, the template wins and the difference is reported.
//
//   node scripts/build-skill.mjs            write the files
//   node scripts/build-skill.mjs --check    exit 1 if the files are stale
//   node scripts/build-skill.mjs --strict   also exit 1 on any source mismatch

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shortcodeDir = join(root, "layouts", "_shortcodes");
const snippetsFile = join(root, ".vscode", "hextra.code-snippets");
const iconsFile = join(root, "data", "icons.yaml");
const outDir = join(root, "skills", "hextra", "references");

const BANNER = (sources) =>
  `<!-- Generated by scripts/build-skill.mjs from ${sources} — do not edit by hand.
     Regenerate with: npm run build:skill -->`;

// ---------------------------------------------------------------------------
// Go template parsing
// ---------------------------------------------------------------------------

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

/** Leading `{{- /* ... *​/ -}}` doc comment, if the file opens with one. */
function docComment(source) {
  const m = source.match(/^\s*\{\{-?\s*\/\*([\s\S]*?)\*\/\s*-?\}\}/);
  return m ? m[1] : "";
}

/**
 * `.Get` calls belonging to the shortcode itself.
 *
 * Two things masquerade as parameter reads and must not be counted: a `.Get`
 * on some other object (`$styles.Get`, `.Page.Store.Get`), which the lookbehind
 * rejects, and a `.Get` inside `{{ with .Parent }}`, where the dot is rebound
 * to the parent shortcode — `accordion-item` reads its parent's `mode` that
 * way. Tracking block depth is enough to spot the second case; the templates
 * never nest a parent scope inside another parent scope.
 */
function ownGetCalls(body) {
  const OPENS = /\{\{-?\s*(if|with|range|block|define)\b([^}]*)\}\}/;
  const ENDS = /\{\{-?\s*end\s*-?\}\}/;
  const GET = /(?<![\w])\.Get\s+(?:"([^"]+)"|(\d+))/g;

  const named = new Map();
  const positional = new Set();
  const parentParams = new Set();

  let depth = 0;
  let parentDepth = null;

  for (const action of body.split(/(?=\{\{)/)) {
    const inParentScope = parentDepth !== null;

    for (const m of action.matchAll(GET)) {
      if (m[2] !== undefined) {
        if (!inParentScope) positional.add(Number(m[2]));
        continue;
      }
      if (inParentScope) parentParams.add(m[1]);
      else if (!named.has(m[1])) named.set(m[1], {});
    }

    const open = action.match(OPENS);
    if (open) {
      if (open[1] === "with" && /\$?\.Parent\b/.test(open[2]) && parentDepth === null) {
        parentDepth = depth;
      }
      depth++;
    } else if (ENDS.test(action)) {
      depth--;
      if (parentDepth !== null && depth <= parentDepth) parentDepth = null;
    }
  }

  return { named, positional, parentParams };
}

/** `.Get "x" | default VALUE` — the default, and any deprecated alias. */
function defaultsFor(body) {
  const out = new Map();
  const re = /(?<![\w])\.Get\s+"([^"]+)"\s*\|\s*default\s+(\([^)]*\)|"[^"]*"|\S+)/g;
  for (const m of body.matchAll(re)) {
    const [, name, raw] = m;
    const alias = raw.match(/\.Get\s+"([^"]+)"/);
    const entry = out.get(name) ?? {};
    if (alias) entry.alias = alias[1];
    else if (/\.Get\s+\d/.test(raw)) entry.positional = true;
    // `| default $someVar` resolves at render time; there is no literal to show.
    else if (!raw.startsWith("$")) entry.default = raw.replace(/^"|"$/g, "");
    out.set(name, entry);
  }
  return out;
}

/** Parameters an `errorf` names as required. */
function requiredFrom(body) {
  const out = new Set();
  for (const m of body.matchAll(/requires (?:a|an|at least one) '([^']+)'/g)) out.add(m[1]);
  for (const m of body.matchAll(/missing required '([^']+)'/g)) out.add(m[1]);
  return out;
}

function parseDoc(comment) {
  const lines = comment.split("\n").map((l) => l.replace(/^\s*/, ""));
  const params = [];
  const positionalDocs = [];
  const examples = [];
  const prose = [];
  const deprecated = [];

  for (const line of lines) {
    const param = line.match(/^@param\s+\{([^}]*)\}\s+(\S+)\s*(.*)$/);
    if (param) {
      // `@param {string} 0` and `0..n` document positional arguments, which
      // are read with `.Get 0` rather than by name.
      //
      // A name may carry both spellings, as in `0|src`: the value can be passed
      // positionally or under that name. Splitting on the bar records each side,
      // so the named half is not lost to the leading digit - it used to be, and
      // the parameter was then reported as undocumented and printed in the
      // reference as "Undocumented in the template" despite being documented.
      const desc = param[3].trim();
      const names = param[2].split("|").filter(Boolean);
      if (names.some((name) => /^\d/.test(name))) positionalDocs.push(desc);
      for (const name of names.filter((name) => !/^\d/.test(name))) {
        params.push({ type: param[1], name, desc });
      }
      continue;
    }
    // `@deprecated name Use `x` instead.` documents a parameter the template
    // still accepts but nobody should reach for: an old spelling kept working,
    // or one that warns at build time. Without it such a parameter looks like an
    // omission to the cross-check, and the reference advertised it as an
    // ordinary parameter with no description and no warning.
    const deprecatedTag = line.match(/^@deprecated\s+(\S+)\s*(.*)$/);
    if (deprecatedTag) {
      deprecated.push({ name: deprecatedTag[1], note: deprecatedTag[2].trim() });
      continue;
    }
    const example = line.match(/^@example\s+(.*)$/);
    if (example) {
      examples.push(example[1].trim());
      continue;
    }
    if (/^@\w+/.test(line)) continue;
    if (params.length === 0 && examples.length === 0) prose.push(line);
  }

  return {
    // The first paragraph is the summary; later paragraphs are implementation
    // notes aimed at theme developers, not at the person writing content.
    description:
      prose
        .join("\n")
        .trim()
        .split(/\n\s*\n/)[0]
        ?.replace(/\s+/g, " ")
        .trim() ?? "",
    params,
    positionalDocs,
    examples,
    deprecated,
  };
}

function parseShortcode(file) {
  const source = readFileSync(file, "utf8");
  const name = relative(shortcodeDir, file)
    .split(sep)
    .join("/")
    .replace(/\.html$/, "");
  const comment = docComment(source);
  const body = source.slice(comment ? source.indexOf(comment) + comment.length : 0);

  const doc = parseDoc(comment);
  const { named, positional, parentParams } = ownGetCalls(body);
  const defaults = defaultsFor(body);
  const required = requiredFrom(body);

  // An `@example` must end in `}}` to be usable; Prettier's Go-template parser
  // reflows a few of them across lines inside the comment.
  const examples = doc.examples.filter((e) => /\}\}\s*$/.test(e) && !/^\w+:/.test(e));

  const documented = new Map(doc.params.map((p) => [p.name, p]));
  const deprecated = new Map(doc.deprecated.map((d) => [d.name, d.note]));
  const paramNames = [...new Set([...named.keys(), ...documented.keys(), ...deprecated.keys()])].sort();

  const params = paramNames.map((pname) => {
    const d = documented.get(pname);
    const meta = defaults.get(pname) ?? {};
    const desc = d?.desc ?? "";
    const inCode = named.has(pname);

    const declaredDefault = desc.match(/\bDefaults? (?:to )?([^.]+)\./i)?.[1];
    const enumFromDesc = desc.match(/\bOne of ([^.]+)\./i)?.[1];

    return {
      name: pname,
      type: d?.type ?? "",
      desc,
      inCode,
      // A deprecated parameter is documented - just not recommended - so it is
      // neither a gap nor an undescribed row.
      documented: Boolean(d) || deprecated.has(pname),
      deprecated: deprecated.get(pname),
      required: required.has(pname) || /\bRequired\b/.test(desc),
      // A default stated in the doc comment is the readable one; fall back to
      // the literal in the template only when the comment says nothing.
      default: declaredDefault?.trim() ?? meta.default,
      alias: meta.alias,
      positionalAlias: Boolean(meta.positional),
      enum: enumFromDesc
        ? enumFromDesc
            .split(/,\s*|\s+or\s+/)
            .map((v) => v.replace(/\(default\)/i, "").trim())
            .filter(Boolean)
        : undefined,
    };
  });

  return {
    name,
    file: relative(root, file),
    description: doc.description,
    params,
    positional: [...positional].sort(),
    positionalDocs: doc.positionalDocs,
    parentParams: [...parentParams],
    examples,
    paired: /(?<![\w])\.Inner(?:Deindent)?\b/.test(body),
    // Notation is a call-site decision, so the only evidence in the template is
    // how its own examples are written.
    percentNotation: doc.examples.some((e) => e.includes("{{%")),
    network: /resources\.GetRemote/.test(body),
    siteParams: [...new Set([...body.matchAll(/(?:site|\.Site)\.Params\.([A-Za-z][\w.]*)/g)].map((m) => m[1].replace(/\.$/, "")))].sort(),
  };
}

