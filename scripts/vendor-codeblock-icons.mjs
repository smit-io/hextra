// Vendors code block file-type icons into data/icons-vendored.yaml so that
// production builds do not depend on the Iconify API at build time.
//
// Reads every `iconify:<set>/<icon>` reference from data/codeblock-icons.yaml,
// fetches the SVGs once from https://api.iconify.design, and writes them keyed
// by their full reference. The `utils/icon` partial checks this file before
// falling back to a remote fetch, so the file is optional but recommended.
//
// Usage: npm run vendor:icons

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mappingFile = join(root, "data", "codeblock-icons.yaml");
const outFile = join(root, "data", "icons-vendored.yaml");

const mapping = readFileSync(mappingFile, "utf8");
const refs = [...new Set([...mapping.matchAll(/:\s*(iconify:\S+)/g)].map((m) => m[1]))].sort();

if (refs.length === 0) {
  console.error(`No iconify references found in ${mappingFile}`);
  process.exit(1);
}

const entries = [];
for (const ref of refs) {
  const path = ref.slice("iconify:".length);
  const url = `https://api.iconify.design/${path}.svg`;
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`Failed to fetch ${url}: ${res.status}`);
    process.exit(1);
  }
  let svg = (await res.text()).trim();
  // Drop fixed dimensions; the icon partial injects its own sizing attributes.
  svg = svg.replace(/(<svg[^>]*?)\s(?:width|height)=("[^"]*"|'[^']*'|[^\s>]+)/g, "$1");
  svg = svg.replace(/(<svg[^>]*?)\s(?:width|height)=("[^"]*"|'[^']*'|[^\s>]+)/g, "$1");
  if (!svg.includes("fill=") && !svg.includes("stroke=")) {
    svg = svg.replace("<svg", '<svg fill="currentColor"');
  }
  entries.push(`"${ref}": >-\n  ${svg}`);
  console.log(`vendored ${ref}`);
}

const header =
  "# Generated by scripts/vendor-codeblock-icons.mjs — do not edit by hand.\n" +
  "# Icons referenced by data/codeblock-icons.yaml, vendored from the Iconify\n" +
  "# API so builds work offline. Regenerate with: npm run vendor:icons\n\n";

writeFileSync(outFile, header + entries.join("\n") + "\n");
console.log(`\nWrote ${entries.length} icons to ${outFile}`);
